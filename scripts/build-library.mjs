// Builds engine/cartoon/library.js from the 2D library folders (briefs: docs/2d-library):
//   engine/cartoon/library/actions/*.json   whole-body actions  → ZANATOMY.addPosture
//   engine/cartoon/library/gestures/*.json  arm moves            → ZANATOMY.addGesture
//   engine/cartoon/library/hands/*.json     hand shapes          → HANDS.addPose
//   engine/cartoon/library/set/*.js         set pieces           → ZS.define(...)
//   engine/cartoon/library/props/*.js       things held or placed → ZS.define(..., { kind: "prop" })
// compose.mjs loads the result after the rest of engine/cartoon. Check new work first: node scripts/library-check.mjs <folder>
// Run: node scripts/build-library.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const LIB_DIR = path.join(root, "engine/cartoon/library");
const OUT = path.join(root, "engine/cartoon/library.js");

const files = (dir, ext) => { try { return fs.readdirSync(dir).filter((f) => f.endsWith(ext)).sort().map((f) => path.join(dir, f)); } catch { return []; } };
const json = (f) => { try { return JSON.parse(fs.readFileSync(f, "utf8")); } catch (e) { throw new Error(`${path.relative(root, f)}: ${e.message}`); } };

// one library folder (the shipped one, or a delivery being checked) → the page's JavaScript
export function libraryJS(dir = LIB_DIR) {
  const actions = files(path.join(dir, "actions"), ".json").map(json);
  const gestures = files(path.join(dir, "gestures"), ".json").map(json);
  const hands = files(path.join(dir, "hands"), ".json").map((f) => ({ name: path.basename(f, ".json"), pose: json(f) }));
  // the world scale's data (engine/cartoon/world.js): real sizes + how tall each drawing comes out; a delivery uses the shipped ones
  const data = (f) => { for (const d of [dir, LIB_DIR]) if (fs.existsSync(path.join(d, f))) return json(path.join(d, f)); return {}; };
  const world = { sizes: data("sizes.json"), drawn: data("drawn.json") };
  const acting = data("acting.json"); delete acting.about; // the acting cards (engine/cartoon/acting.js, ZC.feel)
  // the camera rule book (engine/cartoon/camera.js): only what the page's helpers use (the rest is for the director and the checks)
  const cam = data("camera.json"), camera = cam.sizes ? { landmarks: cam.landmarks, sizes: Object.fromEntries(Object.entries(cam.sizes).map(([k, v]) => [k, { frameTop: v.frameTop, frameBottom: v.frameBottom, footroom: v.footroom, personHeightOfFrame: v.personHeightOfFrame, eyeLine: v.eyeLine, minHold: v.minHold, aliases: v.aliases }])), sizeClassify: cam.sizeClassify, keySafe: { "9:16": cam.formats?.["9:16"]?.safeZones?.keySafe, "16:9": cam.formats?.["16:9"]?.safeZones?.keySafe } } : {};
  const code = ["set", "props"].flatMap((k) => files(path.join(dir, k), ".js").map((f) => `// ${k}/${path.basename(f)}\n${fs.readFileSync(f, "utf8").trim()}`));
  return `// GENERATED by scripts/build-library.mjs from engine/cartoon/library: do not edit by hand.
(function (root) {
  const A = root.ZANATOMY, H = root.HANDS, ZS = root.ZS;
  root.ZWORLD_DATA = ${JSON.stringify(world)};
  root.ZACTING_DATA = ${JSON.stringify(acting)};
  root.ZCAMERA_DATA = ${JSON.stringify(camera)};
  ${JSON.stringify(hands)}.forEach((h) => H && H.addPose(h.name, h.pose));
  ${JSON.stringify(actions)}.forEach((d) => A.addPosture(d));
  ${JSON.stringify(gestures)}.forEach((d) => A.addGesture(d));
  if (ZS) {
${code.join("\n")}
  }
})(typeof window !== "undefined" ? window : globalThis);
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const js = libraryJS();
  fs.writeFileSync(OUT, js);
  const n = (k, ext) => files(path.join(LIB_DIR, k), ext).length;
  console.log(`engine/cartoon/library.js: ${n("actions", ".json")} actions, ${n("gestures", ".json")} gestures, ${n("hands", ".json")} hands, ${n("set", ".js")} set pieces, ${n("props", ".js")} props`);
}
