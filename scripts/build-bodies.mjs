// Turns the body chart (engine/cartoon/library/body-chart.json: real proportions per gender × age, builds) into the engine's body
// profiles: engine/cartoon/bodies.js (root.ZBODIES), read by ZPEOPLE.biometrics. Each dial is solved against the real skeleton
// (engine/cartoon/anatomy.js, measured on its symmetric reference stand), so the drawn body has the chart's ratios. No AI.
// Run after changing the chart or the skeleton's radii:   node scripts/build-bodies.mjs   (then node scripts/cartoon-test.mjs)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
for (const f of ["hands.js", "anatomy.js"]) await import(path.join(root, "engine/cartoon", f));
const A = globalThis.ZANATOMY, R = A.RADII;
const chart = JSON.parse(fs.readFileSync(path.join(root, "engine/cartoon/library/body-chart.json"), "utf8"));
const OUT = path.join(root, "engine/cartoon/bodies.js");

// the cartoon look on top of the real numbers: children's heads a little big (the chart allows up to +15%), arms a touch fuller
// than life so they read at small sizes (never past the chart's cartoon maximum), the elderly with a visible stoop
const HEAD_PLUS = { toddler: 0.15, child6: 0.14, child9: 0.12, child12: 0.07, teen: 0.03, adult: 0, elder: 0 };
const ARM_PLUS = 1.1, STOOP = { elder: 8 };
// the long-garment drape (anatomy.js drape(): aprons over the thighs when squatting, bowing, lying) is tuned for legs and pelvis up
// to the old adult thickness 1.0; adult thighs stay at most that (about 7% under the chart's usual, inside its cartoon range) until
// the drape is retuned for fuller legs
const LEG_MAX = 1.0, PELVIS_MAX = 1.0;
const u = (v) => (Array.isArray(v) ? v[1] : v);
const mid = (a, b) => (a + b) / 2;

function measure(profile) {
  const ps = A.pose({ posture: "neutral", profile }), J = ps.joints, P = ps.profile, r = R.head * P.headScale;
  return { crown: J.head.y + r, heads: (J.head.y + r) / (2 * r), shoulderX: mid(Math.abs(J.shoulderL.x), Math.abs(J.shoulderR.x)), hipX: mid(Math.abs(J.hipL.x), Math.abs(J.hipR.x)) };
}
function solve(rowId, build) {
  const row = chart.rows[rowId], age = rowId.split(".")[1], m = { ...row.measures }, k = build === "average" ? {} : chart.buildOverrides?.[rowId]?.[build] || {};
  const w = (name) => u(m[name]) * (k[name] ?? 1); // a width after the build
  const stature = u(m.stature), ratio = (name) => w(name) / stature, cartoonMax = (name) => row.ratios?.[`${name}/stature`]?.cartoonRange?.[1] ?? Infinity;
  const prof = { base: "adult", scaleY: Math.max(0.55, Math.min(1.15, stature / 1.6)), scaleWidth: 1, kyphosisDeg: STOOP[age] || 0, shoulderWidth: 1, hipWidth: 1, headScale: 0.93 };
  // the head: heads tall from the chart, then the cartoon allowance (a bigger head = fewer heads tall)
  const wantHeads = u(m.headsTall) / (1 + (HEAD_PLUS[age] || 0));
  let lo = 0.5, hi = 1.8;
  for (let i = 0; i < 40; i++) { prof.headScale = (lo + hi) / 2; if (measure(prof).heads > wantHeads) lo = prof.headScale; else hi = prof.headScale; }
  const crown = measure(prof).crown;
  // thickness per part: the chart's front width ÷ stature × the drawn stature ÷ the skeleton's base width there
  const armRatio = Math.min(ratio("upperArmWidth") * ARM_PLUS, cartoonMax("upperArmWidth"));
  prof.armThick = (armRatio * crown) / (R.upperArm[0] + R.upperArm[1]);
  prof.legThick = Math.min(LEG_MAX, (ratio("thighWidth") * crown) / (2 * R.thigh[0]));
  prof.waistThick = (ratio("waistWidth") * crown) / (2 * R.pelvis_lumbar.front[1]);
  prof.chestThick = (ratio("chestWidth") * crown) / (2 * R.lumbar_thorax.front[1]);
  prof.pelvisThick = Math.min(PELVIS_MAX, (ratio("hipWidth") * crown * 0.92) / (2 * R.pelvis_lumbar.front[0])); // the hips' soft outline is the pelvis plus the thigh tops
  prof.limbThick = prof.armThick; // the neck and small straps follow the arms' scale
  // shoulders and hips: move the joints sideways so the outer edges land on the chart's widths
  for (let i = 0; i < 3; i++) {
    const g = measure(prof);
    prof.shoulderWidth *= ((ratio("shoulderWidth") * crown) / 2 - R.upperArm[0] * prof.armThick) / g.shoulderX;
    prof.hipWidth *= ((ratio("hipWidth") * crown) / 2 - R.thigh[0] * prof.legThick) / g.hipX;
  }
  const round = (x) => Math.round(x * 1000) / 1000;
  return Object.fromEntries(Object.entries(prof).map(([key, v]) => [key, typeof v === "number" ? round(v) : v]));
}

const rows = {}, ranges = {};
for (const id of Object.keys(chart.rows)) {
  rows[id] = Object.fromEntries(["average", "thin", "heavy"].map((b) => [b, solve(id, b)]));
  ranges[id] = Object.fromEntries(Object.entries(chart.rows[id].ratios || {}).map(([k, v]) => [k, v.cartoonRange || v.real]));
}
const motion = Object.fromEntries(Object.entries(chart.rows).map(([id, r]) => [id, r.motion]));
fs.writeFileSync(OUT, `// GENERATED by scripts/build-bodies.mjs from engine/cartoon/library/body-chart.json: do not edit by hand.
// ZBODIES.rows["female.adult"].average = the body profile (anatomy.js dials) of that row; ranges = the chart's cartoon ratio ranges
// (scripts/cartoon-test.mjs measures every row and build against them); motion = walking speed, steps, timing by age.
(function (root) {
  root.ZBODIES = ${JSON.stringify({ rows, ranges, motion })};
})(typeof window !== "undefined" ? window : globalThis);
`);
console.log(`engine/cartoon/bodies.js: ${Object.keys(rows).length} rows × 3 builds`);
for (const id of Object.keys(rows)) { const p = rows[id].average; console.log(`  ${id.padEnd(15)} head ${p.headScale}  arm ${p.armThick}  leg ${p.legThick}  chest ${p.chestThick}  waist ${p.waistThick}  pelvis ${p.pelvisThick}  shoulders ${p.shoulderWidth}  hips ${p.hipWidth}`); }
